<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Modules\Products\Images\ProductImageStore;
use DateTimeImmutable;
use DateTimeInterface;
use Illuminate\Console\Command;
use Illuminate\Database\ConnectionInterface;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Random\Engine\Xoshiro256StarStar;
use Random\Randomizer;

/**
 * Requirement 3 (R3-1): fills the Laravel database with a realistic volume
 * of fake history — thousands of products and hundreds of thousands of
 * orders with their lines and status history — so slow queries, missing
 * indexes and N+1 problems show up the way they would in production.
 *
 * Why rows are written directly with multi-row INSERTs instead of going
 * through POST /orders (PlaceOrder):
 *   - this is fake *past* data. Placing an order reserves stock in the
 *     inventory service over gRPC; 200,000 ReserveStock calls would take
 *     hours and would also drain real quantities. The inventory is not
 *     involved in history at all: reservations of delivered or cancelled
 *     orders are long finished.
 *   - one INSERT per 1,000 rows inside one transaction per chunk is three
 *     orders of magnitude faster than one Eloquent save per row.
 *
 * It is a developer tool, like a database dump restore, which is why it sits
 * outside the modules and writes their tables (products, orders,
 * order_items, order_status_history) itself. Application code never does
 * that (docs/01 section 3). Generated products get no stock in the inventory
 * service, so they are shown as out of stock.
 *
 * Non-production only. Additive but guarded: a second run is refused while
 * generated products exist. Deterministic for a given --seed.
 */
final class PerfSeed extends Command
{
    /** Description of every generated product: how a run is recognised. */
    public const string MARKER = 'Generated by app:perf-seed for load testing.';

    private const int CHUNK = 1000;

    private const string TIME_FORMAT = 'Y-m-d H:i:sP';

    protected $signature = 'app:perf-seed
        {--orders=200000 : Orders to generate}
        {--products=2000 : Products to generate}
        {--seed=2026 : Random seed (same seed, same data)}';

    protected $description = 'Bulk-insert fake products and order history for load testing (non-production only)';

    public function handle(ProductImageStore $images): int
    {
        if ($this->laravel->environment('production')) {
            $this->components->error('app:perf-seed is refused in production.');

            return self::FAILURE;
        }

        $orders = (int) $this->option('orders');
        $productCount = (int) $this->option('products');

        if ($orders < 0 || $productCount < 1) {
            $this->components->error('--orders must be >= 0 and --products >= 1.');

            return self::FAILURE;
        }

        $db = DB::connection();

        if ($db->table('products')->where('description', self::MARKER)->exists()) {
            $this->components->warn('Generated data already exists; nothing done.');

            return self::SUCCESS;
        }

        /** @var list<string> $categories */
        $categories = $db->table('categories')->orderBy('slug')->pluck('id')->all();
        /** @var list<string> $customers */
        $customers = $db->table('users')->where('role', 'customer')->orderBy('email')->pluck('id')->all();
        $admin = $db->table('users')->where('role', 'admin')->orderBy('created_at')->value('id');

        if ($categories === [] || $customers === [] || ! is_string($admin)) {
            $this->components->error('Categories, customers and an admin are required: run `make bootstrap` first.');

            return self::FAILURE;
        }

        $random = new Randomizer(new Xoshiro256StarStar((int) $this->option('seed')));
        $now = new DateTimeImmutable('now');
        $started = hrtime(true);

        $products = $this->seedProducts($db, $random, $now, $productCount, $categories, $this->imageName($db, $images));
        $this->components->twoColumnDetail('products', (string) count($products));

        $lines = $this->seedOrders($db, $random, $now, $orders, $products, $customers, $admin);
        $this->components->twoColumnDetail('orders', (string) $orders);
        $this->components->twoColumnDetail('order lines', (string) $lines);

        $db->statement('ANALYZE products, orders, order_items, order_status_history');
        $this->components->info(sprintf('Done in %.1f s.', (hrtime(true) - $started) / 1e9));

        return self::SUCCESS;
    }

    /**
     * One stored WebP shared by every generated product: an existing
     * product's image, or the demo book photo encoded once.
     */
    private function imageName(ConnectionInterface $db, ProductImageStore $images): string
    {
        $existing = $db->table('products')->orderBy('created_at')->value('image');

        if (is_string($existing)) {
            return $existing;
        }

        $path = base_path('database/demo-catalog/book.jpg');

        return $images->store(new UploadedFile($path, 'book.jpg', 'image/jpeg', null, true));
    }

    /**
     * @param  list<string>  $categories
     * @return list<array{id: string, name: string, price: int}>
     */
    private function seedProducts(ConnectionInterface $db, Randomizer $random, DateTimeImmutable $now, int $count, array $categories, string $image): array
    {
        $products = [];

        for ($offset = 0; $offset < $count; $offset += self::CHUNK) {
            $rows = [];

            for ($n = $offset + 1; $n <= min($count, $offset + self::CHUNK); $n++) {
                // Spread over the last year, always in the past, so products
                // created live (demo catalogue, race test) stay on page 1.
                $created = $this->minutesAgo($now, $random->getInt(60 * 24, 60 * 24 * 365));
                $id = $this->ulid($created);
                $price = $random->getInt(10, 50_000) * 100;
                $name = sprintf('PERF product %05d', $n);

                $rows[] = [
                    'id' => $id,
                    'name' => $name,
                    'description' => self::MARKER,
                    'price_minor' => $price,
                    'currency' => 'SYP',
                    'category_id' => $categories[$random->getInt(0, count($categories) - 1)],
                    'image' => $image,
                    'created_at' => $created->format(self::TIME_FORMAT),
                    'updated_at' => $created->format(self::TIME_FORMAT),
                ];
                $products[] = ['id' => $id, 'name' => $name, 'price' => $price];
            }

            $db->table('products')->insert($rows);
        }

        return $products;
    }

    /**
     * Orders of the last ~13 months with 1-4 distinct lines and a history
     * that follows the state machine (pending → confirmed → shipped →
     * delivered, or cancelled from pending/confirmed by the admin).
     *
     * @param  list<array{id: string, name: string, price: int}>  $products
     * @param  list<string>  $customers
     * @return int order lines written
     */
    private function seedOrders(ConnectionInterface $db, Randomizer $random, DateTimeImmutable $now, int $count, array $products, array $customers, string $admin): int
    {
        $lines = 0;
        $bar = $this->output->createProgressBar($count);

        for ($offset = 0; $offset < $count; $offset += self::CHUNK) {
            $orders = [];
            $items = [];
            $history = [];

            for ($n = $offset; $n < min($count, $offset + self::CHUNK); $n++) {
                // At least 5 days old: the last history entry (at most +3 days)
                // is still in the past.
                $created = $this->minutesAgo($now, $random->getInt(60 * 24 * 5, 60 * 24 * 400));
                $id = $this->ulid($created);
                $customer = $customers[$random->getInt(0, count($customers) - 1)];

                $total = 0;
                $picked = [];
                $lineCount = $random->getInt(1, min(4, count($products)));
                while (count($picked) < $lineCount) {
                    $picked[$random->getInt(0, count($products) - 1)] = true;
                }
                foreach (array_keys($picked) as $index) {
                    $product = $products[$index];
                    $quantity = $random->getInt(1, 3);
                    $total += $product['price'] * $quantity;
                    $items[] = [
                        'order_id' => $id,
                        'product_id' => $product['id'],
                        'product_name' => $product['name'],
                        'unit_price_minor' => $product['price'],
                        'quantity' => $quantity,
                    ];
                }
                $lines += $lineCount;

                $steps = $this->path($random->getInt(1, 100));
                $from = null;
                $at = $created;
                foreach ($steps as $step => $to) {
                    $at = $step === 0 ? $created : $at->modify('+'.$random->getInt(10, 1440).' minutes');
                    $history[] = [
                        'order_id' => $id,
                        'from_status' => $from,
                        'to_status' => $to,
                        'actor_id' => $step === 0 ? $customer : $admin,
                        'actor_role' => $step === 0 ? 'customer' : 'admin',
                        'note' => null,
                        'at' => $at->format(self::TIME_FORMAT),
                    ];
                    $from = $to;
                }

                $orders[] = [
                    'id' => $id,
                    'user_id' => $customer,
                    'status' => $from,
                    'total_minor' => $total,
                    'currency' => 'SYP',
                    'created_at' => $created->format(self::TIME_FORMAT),
                    'updated_at' => $at->format(self::TIME_FORMAT),
                ];
            }

            $db->transaction(function () use ($db, $orders, $items, $history): void {
                $db->table('orders')->insert($orders);
                $db->table('order_items')->insert($items);
                $db->table('order_status_history')->insert($history);
            });
            $bar->advance(count($orders));
        }

        $bar->finish();
        $this->newLine();

        return $lines;
    }

    /**
     * Status path for a percentile roll: 10% pending, 10% confirmed, 15%
     * shipped, 55% delivered, 5% cancelled while pending, 5% after
     * confirmation.
     *
     * @return non-empty-list<string>
     */
    private function path(int $roll): array
    {
        return match (true) {
            $roll <= 10 => ['pending'],
            $roll <= 20 => ['pending', 'confirmed'],
            $roll <= 35 => ['pending', 'confirmed', 'shipped'],
            $roll <= 90 => ['pending', 'confirmed', 'shipped', 'delivered'],
            $roll <= 95 => ['pending', 'cancelled'],
            default => ['pending', 'confirmed', 'cancelled'],
        };
    }

    private function minutesAgo(DateTimeImmutable $now, int $minutes): DateTimeImmutable
    {
        return $now->modify('-'.$minutes.' minutes');
    }

    /**
     * Canonical upper-case ULID whose time part is the row's creation time,
     * so ids sort like created_at, as for rows created by the API.
     */
    private function ulid(DateTimeInterface $at): string
    {
        return strtoupper((string) Str::ulid($at));
    }
}
