package com.ecommerce.inventory.grpc;

import com.ecommerce.inventory.domain.ReservationLine;
import com.ecommerce.inventory.grpc.v1.ReservationItem;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.UUID;
import java.util.regex.Pattern;

/**
 * Input rules of the gRPC contract (inventory.proto, docs/03 section 3). Every violation is an
 * {@link InvalidRequestException} whose message names the field, never the value sent.
 */
final class RequestValidator {

  /** ULID as in the OpenAPI {@code Ulid} schema: 26 Crockford base32 characters, upper case. */
  private static final Pattern ULID = Pattern.compile("[0-7][0-9A-HJKMNP-TV-Z]{25}");

  /** Canonical lower-case text form of a UUID (RFC 9562), as generated by the caller. */
  private static final Pattern UUID_TEXT =
      Pattern.compile("[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}");

  static final int MAX_PRODUCT_IDS = 100;
  static final int MAX_ITEMS = 100;
  static final int MAX_QUANTITY = 1000;

  private RequestValidator() {}

  /** reservation_id / adjustment_id: canonical lower-case UUID. */
  static UUID uuid(String field, String value) {
    if (!UUID_TEXT.matcher(value).matches()) {
      throw new InvalidRequestException(field + " must be a lower-case canonical UUID");
    }
    return UUID.fromString(value);
  }

  /** ReserveStock items: 1..100 lines, distinct ULIDs, quantity 1..1000. */
  static List<ReservationLine> reservationItems(List<ReservationItem> items) {
    requireCount("items", items.size(), MAX_ITEMS);
    Set<String> seen = new HashSet<>();
    List<ReservationLine> lines = new ArrayList<>(items.size());
    for (int i = 0; i < items.size(); i++) {
      ReservationItem item = items.get(i);
      String field = "items[" + i + "]";
      String productId = productId(field + ".product_id", item.getProductId());
      if (item.getQuantity() < 1 || item.getQuantity() > MAX_QUANTITY) {
        throw new InvalidRequestException(
            field + ".quantity must be between 1 and " + MAX_QUANTITY);
      }
      if (!seen.add(productId)) {
        throw new InvalidRequestException(field + ".product_id is a duplicate");
      }
      lines.add(new ReservationLine(productId, item.getQuantity()));
    }
    return List.copyOf(lines);
  }

  /** GetStock: 1..100 product ULIDs without duplicates. */
  static List<String> productIds(List<String> productIds) {
    requireCount("product_ids", productIds.size(), MAX_PRODUCT_IDS);
    Set<String> seen = new HashSet<>();
    for (int i = 0; i < productIds.size(); i++) {
      String field = "product_ids[" + i + "]";
      String id = productId(field, productIds.get(i));
      if (!seen.add(id)) {
        throw new InvalidRequestException(field + " is a duplicate");
      }
    }
    return List.copyOf(productIds);
  }

  static String productId(String field, String value) {
    if (!ULID.matcher(value).matches()) {
      throw new InvalidRequestException(
          field + " must be a ULID (26 upper-case Crockford base32 characters)");
    }
    return value;
  }

  static void requireCount(String field, int count, int max) {
    if (count < 1 || count > max) {
      throw new InvalidRequestException(field + " must contain 1 to " + max + " entries");
    }
  }
}
